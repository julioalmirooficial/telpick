/**
 * Generates src/flags-imports.js with one import per flag so the consumer's
 * bundler can include the assets. Run before build (or via Vite plugin).
 */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const countryCodePath = join(root, 'src', 'assets', 'country-code.json');
const outPath = join(root, 'src', 'flags-imports.js');

const data = JSON.parse(readFileSync(countryCodePath, 'utf8'));
const seen = new Set();
const entries = [];
for (const item of data) {
  const key = (item.country_code || '').toLowerCase();
  if (!key || seen.has(key)) continue;
  seen.add(key);
  const filename = (item.flag || '').replace(/^.*\//, '') || `${key}.webp`;
  entries.push({ key, filename });
}

const imports = entries
  .map(({ key, filename }) => `import ${key} from './assets/flags/${filename}?url'`)
  .join('\n');
const exportObj = entries.map(({ key }) => key).join(', ');

const content = `// Generated by scripts/generate-flags-imports.js – do not edit
${imports}

export default { ${exportObj} }
`;

writeFileSync(outPath, content, 'utf8');
console.log('Generated src/flags-imports.js with', entries.length, 'flags');
